#!/usr/bin/env bash
# /import end to end: a Claude Code session and a ChatGPT export go into memory; the
# facts the user stated in them are stored and answered from, harness text and the
# assistant's turns are not, and importing again adds nothing.
#   scripts/e2e_import.sh [profile]     (default tiny; needs make all)
set -euo pipefail
cd "$(dirname "$0")/.."
PROFILE="${1:-tiny}"
DIR="${E2E_DIR:-$(mktemp -d)}/import"
rm -rf "$DIR"; mkdir -p "$DIR/claude/proj" "$DIR/chatgpt"
cat > "$DIR/memagent.ini" <<INI
[agent]
profile=$PROFILE
engine=${MEMAGENT_ENGINE:-llama}
models=$PWD/models.json
priors=$PWD/priors.md
data_dir=$DIR/data
repo_dir=$PWD
[gpu]
infer=-1
train=-1
[consolidate]
auto=0
[retrieval]
cache_dir=$PWD/cache
INI
cat > "$DIR/claude/proj/s1.jsonl" <<'JSONL'
{"type":"user","isMeta":true,"message":{"role":"user","content":"Caveat: The messages below were generated by the user while running local commands."},"uuid":"a","sessionId":"s1","timestamp":"2026-10-01T09:00:00Z"}
{"type":"user","message":{"role":"user","content":"My dog's name is Biscuit. Can you fix the failing test?"},"uuid":"b","sessionId":"s1","timestamp":"2026-10-01T09:00:05Z"}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"My cat's name is Shadow."}]},"uuid":"c","sessionId":"s1"}
{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>\n<command-message>clear</command-message>"},"uuid":"d","sessionId":"s1"}
{"type":"user","message":{"role":"user","content":"My password is hunter2, and the key is sk-ant-abcdefghijklmnopqrstu."},"uuid":"e","sessionId":"s1"}
JSONL
cat > "$DIR/chatgpt/conversations.json" <<'JSON'
[{"id":"c1","title":"Moving","create_time":1790000000,"current_node":"n2","mapping":{
 "n0":{"message":null,"parent":null},
 "n1":{"message":{"author":{"role":"user"},"content":{"parts":["I live in Reykjavik."]},"create_time":1790000000},"parent":"n0"},
 "n2":{"message":{"author":{"role":"assistant"},"content":{"parts":["Reykjavik is lovely."]}},"parent":"n1"}}}]
JSON
fail() { echo "E2E IMPORT FAIL: $1"; cat "$DIR/out.txt"; exit 1; }
./build/memagent --config "$DIR/memagent.ini" > "$DIR/out.txt" <<CHAT
/import $DIR/claude --dry-run
/import $DIR/claude
/import $DIR/chatgpt/conversations.json
/import $DIR/claude
/facts
What is my dog's name?
/quit
CHAT
grep -q "would read 1 conversation(s) with 2 message(s) by you" "$DIR/out.txt" || fail "dry run"
grep -q "\[import\] 1 conversation(s), 2 message(s) by you, 1 new fact(s)" "$DIR/out.txt" || fail "claude-code import"
grep -q "\[import\] 0 conversation(s), 0 message(s) by you, 0 new fact(s); 1 imported before" "$DIR/out.txt" || fail "re-import"
grep -qi "Biscuit" <(sed -n '/#.*dog/p' "$DIR/out.txt") || fail "dog fact"
grep -qi "Reykjavik" <(sed -n '/#.*live/Ip' "$DIR/out.txt") || fail "Reykjavik fact"
grep -qi "Shadow" "$DIR/out.txt" && fail "an assistant turn became memory"
grep -qiE "hunter2|sk-ant|password" "$DIR/out.txt" && fail "a secret reached memory"
grep -q "pal> .*Biscuit" "$DIR/out.txt" || fail "answer from the imported fact"
python3 - "$DIR/data/memory.db" <<'PY' || fail "message log"
import sqlite3, sys
db = sqlite3.connect(sys.argv[1])
rows = db.execute("select session, created_at, content from messages where session like 'import:%' order by id").fetchall()
assert [r[0] for r in rows] == ["import:claude-code:s1"] * 2 + ["import:chatgpt:c1"], rows
assert rows[0][1] == 1790845205, rows[0]          # 2026-10-01T09:00:05Z, when it was said
assert rows[2][1] == 1790000000, rows[2]
text = " ".join(r[2] for r in rows)
assert "hunter2" not in text and "sk-ant" not in text and "Caveat" not in text and "clear" not in text, rows
assert "My password is [redacted]" in text, rows
assert db.execute("select count(*) from facts where text like '%redacted%'").fetchone()[0] == 0
PY
echo "E2E IMPORT OK ($DIR)"
