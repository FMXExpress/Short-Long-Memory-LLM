"""Writes memagent/Mem.ExtractRules.inc, the Pascal copy of memlib.EXTRA_RULES.

The rule table lives once, in trainer/memlib.py; Mem.Extract includes the
generated table, and extract_test.lpr checks both extractors agree:
  python3 memagent/tests/gen_extract_rules.py > memagent/Mem.ExtractRules.inc
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "trainer"))
import memlib  # noqa: E402


def lit(s):
    """A Pascal string literal; UTF-8 bytes pass through as they are."""
    return "'" + s.replace("'", "''") + "'"


rules = memlib.EXTRA_RULES
print("{ generated by memagent/tests/gen_extract_rules.py from trainer/memlib.py EXTRA_RULES: do not edit }")
print(f"const\n  EXTRA_RULES: array[0..{len(rules) - 1}] of TExtraRule = (")
for k, (pattern, caseless, vg, text, subject, questions, check) in enumerate(rules):
    assert len(questions) == 6, pattern
    qs = ", ".join(lit(q) for q in questions)
    print(f"    (Pattern: {lit(pattern)}; Caseless: {str(caseless)}; ValueGroup: {vg};\n"
          f"     Text: {lit(text)}; Subject: {lit(subject)}; Proper: {str(check == 'proper')};\n"
          f"     Questions: ({qs}))" + ("," if k < len(rules) - 1 else ""))
print("  );")
